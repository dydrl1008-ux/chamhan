// 한국 공휴일 (대체공휴일 포함). 음력 기반(설·추석·석탄일)은 연도별로 적어둠 — 매년 12월에 다음 해 추가
const FIXED: [string, string][] = [['01-01', '신정'], ['03-01', '삼일절'], ['05-05', '어린이날'], ['06-06', '현충일'], ['08-15', '광복절'], ['10-03', '개천절'], ['10-09', '한글날'], ['12-25', '성탄절']];
const BY_YEAR: Record<string, Record<string, string>> = {
  '2026': { '02-16': '설날 연휴', '02-17': '설날', '02-18': '설날 연휴', '03-02': '대체공휴일(삼일절)', '05-24': '부처님오신날', '05-25': '대체공휴일(부처님오신날)', '06-03': '지방선거', '09-24': '추석 연휴', '09-25': '추석', '09-26': '추석 연휴', '10-05': '대체공휴일(개천절)' },
  '2027': { '02-06': '설날 연휴', '02-07': '설날', '02-08': '설날 연휴', '02-09': '대체공휴일(설날)', '03-03': '대체공휴일(삼일절)', '05-13': '부처님오신날', '08-16': '대체공휴일(광복절)', '09-14': '추석 연휴', '09-15': '추석', '09-16': '추석 연휴', '10-04': '대체공휴일(개천절)', '10-11': '대체공휴일(한글날)', '12-27': '대체공휴일(성탄절)' },
};
/** 'YYYY-MM-DD' → 공휴일 이름 또는 null */
export function holidayName(d: string): string | null {
  const y = d.slice(0, 4), md = d.slice(5);
  return BY_YEAR[y]?.[md] ?? FIXED.find(([m]) => m === md)?.[1] ?? null;
}
export const isWeekend = (d: string) => { const w = new Date(d + 'T00:00:00Z').getUTCDay(); return w === 0 || w === 6; };
export const isOffDay = (d: string) => isWeekend(d) || !!holidayName(d);
